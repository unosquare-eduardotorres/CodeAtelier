/**
 * design-report.service — renders a design run into the markdown report file
 * Impeccable itself expects: `<workspace>/.impeccable/critique/<file>.md`.
 *
 * Future `/impeccable` sessions discover tracked review artifacts in that
 * directory, so writing there makes the app's design runs part of the same
 * convention. The report is regenerable at any time from the DB (the run row
 * plus its result rows are the source of truth).
 */

import { mkdir, writeFile } from 'node:fs/promises'
import { join, isAbsolute, relative } from 'node:path'
import type { AuditRun, AuditResult, AuditFinding } from '../../shared/types'
import { auditRepository, workspaceRepository } from '../db/repositories'
import { mainLogger } from '../logger'

const log = mainLogger

/** Session map runId → written report path (the file itself is regenerable). */
const reportPaths = new Map<string, string>()

export function getReportPath(runId: string): string | null {
  return reportPaths.get(runId) ?? null
}

// ── Rendering (pure — unit-testable without touching the FS) ──

function scopeLabel(run: AuditRun): string {
  const scope = run.designConfig?.scope
  if (!scope) return 'project'
  if (scope.mode === 'project') return 'whole project'
  return scope.paths.join(', ')
}

function slugify(text: string): string {
  return (
    text
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 60) || 'run'
  )
}

/** Deterministic file name: date + commands + scope slug. */
export function reportFileName(run: AuditRun): string {
  const date = new Date(run.createdAt).toISOString().slice(0, 10)
  const commands = (run.designConfig?.commandIds ?? ['design']).join('-')
  return `${date}__${slugify(commands)}__${slugify(scopeLabel(run))}.md`
}

function renderFinding(f: AuditFinding, index: number): string {
  const lines = [`${index}. **[${f.severity.toUpperCase()}]** ${f.title}`, '', f.description]
  if (f.filePath) lines.push(`\`${f.filePath}\``)
  if (f.recommendation) lines.push(`> ${f.recommendation}`)
  if (f.source) lines.push(`_source: ${f.source}_`)
  return lines.join('\n')
}

export function renderDesignReport(run: AuditRun): string {
  const out: string[] = []
  const cfg = run.designConfig

  out.push(`# Design audit report — ${run.createdAt.slice(0, 10)}`)
  out.push(
    `**Commands:** ${cfg?.commandIds.join(', ') ?? '—'}  \n**Scope:** ${scopeLabel(run)}  \n**Status:** ${run.status}`
  )
  if (cfg?.brief) out.push(`## Brief\n\n> ${cfg.brief}`)

  for (const result of run.results as AuditResult[]) {
    const command = result.trackId.replace(/^design:/, '')
    out.push(`## ${command}`)
    if (result.score != null) out.push(`**Score:** ${result.score}/100`)
    if (result.summary) out.push(result.summary)
    if (result.findings.length > 0) {
      out.push(result.findings.map((f, i) => renderFinding(f, i + 1)).join('\n\n'))
    } else {
      out.push('_No findings._')
    }
  }

  out.push('---')
  out.push(
    `_Generated by Code Atelier · design run \`${run.id}\` · ` +
      `regenerate from the Audit Design history._`
  )
  return out.join('\n\n')
}

// ── Writing ──

export async function writeDesignReport(
  workspacePath: string,
  run: AuditRun
): Promise<string | null> {
  try {
    const dir = join(workspacePath, '.impeccable', 'critique')
    await mkdir(dir, { recursive: true })
    const path = join(dir, reportFileName(run))
    await writeFile(path, renderDesignReport(run), 'utf8')
    reportPaths.set(run.id, path)
    log.info(`[design:report] wrote ${path}`)
    return path
  } catch (err) {
    log.warn('[design:report] write failed:', err)
    return null
  }
}

/** Regenerate + write the report for a persisted run. Returns the path. */
export async function generateReportForRun(
  runId: string
): Promise<{ path: string | null; error?: string }> {
  const run = auditRepository.findRunById(runId)
  if (!run) return { path: null, error: `design run ${runId} not found` }
  if (run.kind !== 'design') return { path: null, error: `run ${runId} is not a design run` }

  const workspace = workspaceRepository.findById(run.workspaceId)
  const workspacePath = workspace?.repoPath
  if (!workspacePath) {
    return { path: null, error: `workspace ${run.workspaceId} has no repo path` }
  }

  const path = await writeDesignReport(workspacePath, run)
  return path ? { path } : { path: null, error: 'report write failed' }
}

/** Repo-relative path for renderer display (the absolute path stays in main). */
export function displayPath(workspacePath: string, absPath: string): string {
  if (!isAbsolute(absPath)) return absPath
  const rel = relative(workspacePath, absPath)
  return rel && !rel.startsWith('..') ? rel : absPath
}
