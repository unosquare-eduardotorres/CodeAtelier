/**
 * CLIExecutor — replaces SDKExecutor for interactive Claude CLI sessions.
 *
 * Spawns `claude` (WITHOUT `-p`) in interactive mode with `--output-format stream-json
 * --input-format stream-json --verbose`. This uses the Claude Max subscription for
 * billing (not the Agent SDK credit pool). The process stays alive for the entire
 * conversation lifetime. User messages are written to stdin as NDJSON lines; NDJSON
 * events are read from stdout and normalized via the same stream-normalizer pipeline.
 *
 * Key design points:
 * - Uses `child_process.spawn('claude', args)` directly — no SDK dependency
 * - Session ID captured from `system/init` event (same NDJSON shape)
 * - Resume via `--resume <sessionId>` CLI flag
 * - Slash commands (/compact, /clear) supported via stdin writes
 * - MCP servers configured via `--mcp-config <path>` (external stdio processes)
 *
 * Introduced for the Agent SDK → CLI migration (June 2026) to avoid
 * Agent SDK credit consumption under the new billing model.
 */

import { spawn, type ChildProcess } from 'node:child_process'
import { writeFileSync, mkdirSync, existsSync, unlinkSync } from 'node:fs'
import { app } from 'electron'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import type { StreamChunk } from './agent-base.service'
import { parseNdjsonStream, writeNdjsonMessage, buildUserMessage } from './cli-executor/ndjson-parser'
import {
  HeartbeatMonitor,
  TokenAccountant,
  TelemetryRecorder,
  ToolTracker,
  normalizeMessage,
  executorLog
} from './executor-utils/index'
import type { StreamState } from './executor-utils/index'

// ── Re-export types for external consumers ──
export type { TelemetryEntry } from './executor-utils/telemetry-recorder'
